const express = require("express");
const controller = require("../controllers/adoptionapplicationadmincontroller");
const { validateid } = require("../utils/validation");
const { authenticated, admin } = require("../middleware");
const router = express.Router();
router.use(authenticated, admin);
router.param("id", validateid);
router.get("/", controller.getadminadoptionapplications);
router.get("/:id", controller.getupdateadoptionapplication);
router.patch("/:id/status", controller.updateadoptionapplication);
module.exports = { router };
