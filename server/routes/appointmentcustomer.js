const express = require("express");
const controller = require("../controllers/appointmentcustomercontroller");
const { validateid } = require("../utils/validation");
const { authenticated, customer } = require("../middleware");
const router = express.Router();
router.use(authenticated, customer);
router.param("id", validateid);
router.get("/", controller.readappointments);
router.post("/", controller.createappointment);
router.delete("/", controller.deletecustomerappointment);
router.get("/:id", controller.readappointment);
router.patch("/:id", controller.updatecustomerappointment);
router.delete("/:id", controller.deletecustomerappointment);
module.exports = { router };
