const express = require("express");
const controller = require("../controllers/listingcustomercontroller");
const { authenticated, customer } = require("../middleware");
const { validateid } = require("../utils/validation");
const router = express.Router();
router.use(authenticated, customer);
router.param("id", validateid);
router.get("/books", controller.index);
router.post("/books", controller.create);
router.delete("/books", controller.withdraw);
router.get("/books/:id", controller.read);
router.patch("/books/:id", controller.update);
router.delete("/books/:id", controller.withdraw);
router.get("/books/:id/applications", controller.requests);
router.patch("/applications/:id/status", controller.decide);
router.get("/collections", controller.collections);
router.get("/collections/:id", controller.collection);
router.patch("/collections/:id", controller.updatecollection);
module.exports = { router };
